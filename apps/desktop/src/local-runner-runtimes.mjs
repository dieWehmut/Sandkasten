// Canonical catalog shared by desktop execution and the real language matrix.
import { fileURLToPath } from 'node:url';

const helper = fileURLToPath(new URL('./local-runner-tools.mjs', import.meta.url));
const script = (label, command, extensions, args = ['{file}'], probe = ['--version']) => ({ label, command, args, probe, extensions });
const native = (label, command, extensions, args = ['{file}', '-o', '{exe}'], probe = ['--version']) => ({
  label, compile: { command, args }, run: { command: '{exe}', args: [] }, probe, extensions,
});
const tool = (label, language, extensions, requirements = []) => ({
  label,
  compile: { command: process.execPath, args: [helper, language, 'build', '{file}', '{exe}'] },
  run: { command: process.execPath, args: [helper, language, 'run', '{file}', '{exe}'] },
  probe: [helper, language, 'probe'], extensions, requirements,
});

