pub(crate) fn normalize_language(language: &str) -> Option<String> {
    let normalized = language.trim().to_ascii_lowercase();
    let canonical = match normalized.as_str() {
        "go" | "golang" => "go",
        "assembly" | "asm" | "gas" | "nasm" => "assembly",
        "bash" | "shell" | "sh" => "bash",
        "c" => "c",
        "cangjie" | "cj" | "cjc" | "仓颉" => "cangjie",
        "clojure" | "clj" => "clojure",
        "cpp" | "c++" => "cpp",
        "css" => "css",
        "csharp" | "cs" | "c#" => "csharp",
        "coq" | "coqtop" | "coqc" => "coq",
        "crystal" | "cr" => "crystal",
        "dart" => "dart",
        "elixir" | "ex" | "exs" => "elixir",
        "erlang" | "erl" | "erts" => "erlang",
        "fsharp" | "f#" | "fs" | "f-sharp" | "f_sharp" => "fsharp",
        "fortran" | "f90" | "gfortran" => "fortran",
        "gdscript" | "gd" | "godot" | "godot3" => "gdscript",
        "gleam" | "gleamlang" => "gleam",
        "graphviz" | "dot" | "gv" => "graphviz",
        "haskell" | "hs" | "ghc" => "haskell",
        "html" | "htm" => "html",
        "java" => "java",
        "javascript" | "js" | "node" => "javascript",
        "julia" | "jl" => "julia",
        "kotlin" | "kt" => "kotlin",
        "lean" | "lean4" => "lean4",
        "latex" | "tex" => "latex",
        "lua" | "lua5.4" => "lua",
        "markdown" | "md" => "markdown",
        "mdx" => "mdx",
        "mojo" | "mojolang" => "mojo",
        "next" | "nextjs" | "next.js" => "nextjs",
        "nextflow" | "nf" => "nextflow",
        "nim" | "nimrod" => "nim",
        "octave" | "gnu-octave" | "m" => "octave",
        "ocaml" | "ml" | "ocamlopt" => "ocaml",
        "pascal" | "fpc" | "freepascal" => "pascal",
        "perl" | "perl5" => "perl",
        "php" | "php8" | "php8.2" => "php",
        "prolog" | "pl" | "swi-prolog" | "swipl" => "prolog",
        "python" | "py" | "python3" => "python",
        "qml" | "qtqml" | "qml5" | "qml6" => "qml",
        "r" | "rscript" => "r",
        "racket" | "rkt" => "racket",
        "ruby" | "rb" => "ruby",
        "rust" | "rs" => "rust",
        "scala" | "sc" => "scala",
        "scss" | "sass" => "scss",
        "sql" | "sqlite" | "sqlite3" => "sql",
        "swift" => "swift",
        "tailwind" | "tailwindcss" | "tailwind-css" => "tailwindcss",
        "typescript" | "ts" => "typescript",
        "tsx" | "jsx" | "react" | "react-tsx" => "tsx",
        "typst" | "typ" => "typst",
        "vlang" | "v" | "v-language" => "vlang",
        "vue" | "vue3" | "vuejs" => "vue3",
        "wdl" | "workflow-description-language" => "wdl",
        "zig" => "zig",
        _ => return None,
    };
    Some(canonical.to_owned())
}
